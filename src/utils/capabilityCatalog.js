// What the system can do, in the words the people using it ask for it. This is the
// only thing the help assistant answers from (services/assistant.service.js).
//
// Who may do each thing is NOT written here. Every entry names the API routes that
// implement it (`routes`), and the assistant reads the allowed roles straight off those
// routes' guards (utils/permissionMatrix.js) — so the bot cannot promise a role something
// the server would refuse. tests/assistant.test.js fails if a route listed here does not
// exist, or if a mounted admin area has no entry, so this file cannot silently drift.
//
// Writing an entry:
//   id        stable slug
//   area      a key of AREAS below
//   title     what the person is trying to do, as a verb phrase
//   summary   one sentence: what it is and what it does
//   keywords  the words and phrases people actually type (synonyms, slang, the old name)
//   routes    'METHOD /full/path' for every route the feature needs (all must be allowed)
//   page      the admin page to link to (optional)
//   steps     numbered how-to, using the on-screen labels
//   notes     rules and gotchas the guards cannot express (optional)
//
// `NOT_SUPPORTED` lists things people reasonably expect and the system does not do.
// Only add one after confirming there is no route or page for it.

